#!/usr/bin/env python3
"""Score actual Three.js WebGL pixels against a controlled synthetic reference.

This is an integration control, not a user-photo fidelity benchmark. A browser
generated the reference and two candidate renders; one is identical, the other
deliberately displaced. No estimated depth or provider inference is claimed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from forge.stage1_intake.extract_pbr_evidence import read_png
from forge.stage1_intake.reconstruction_evidence import load_bundle
from forge.stage4_review.evidence_silhouette import prepare_silhouette
from forge.stage4_review.fit_params import FitConfig, fit_against_divine_eye
from forge.stage4_review.reconstruction_evidence_ab import compare_shadow_runs

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)


def png_bytes(width: int, height: int, bit_depth: int, color_type: int, rows: list[bytes]) -> bytes:
    if width <= 0 or height <= 0 or len(rows) != height:
        raise ValueError("invalid PNG dimensions or rows")
    channels = {0: 1, 2: 3}[color_type]
    expected_row_length = width * channels * (bit_depth // 8)
    if any(len(row) != expected_row_length for row in rows):
        raise ValueError("invalid PNG row length")
    header = struct.pack(">IIBBBBB", width, height, bit_depth, color_type, 0, 0, 0)
    raw = b"".join(b"\x00" + row for row in rows)
    return (PNG_SIGNATURE + chunk(b"IHDR", header)
            + chunk(b"IDAT", zlib.compress(raw, 6)) + chunk(b"IEND", b""))


def artifact(root: Path, role: str, filename: str, payload: bytes, width: int, height: int,
             encoding: str, provenance: dict, **extra) -> dict:
    (root / filename).write_bytes(payload)
    return {
        "role": role, "state": "generated", "relativePath": filename,
        "sha256": hashlib.sha256(payload).hexdigest(),
        "dimensions": {"width": width, "height": height},
        "encoding": encoding, "provenance": provenance, **extra,
    }


def build_synthetic_bundle(root: Path, source_render: Path) -> tuple[Path, Path, int]:
    width, height, pixels = read_png(source_render)
    if width != 224 or height != 224:
        raise ValueError("browser reference must be exactly 224x224")
    fg = [alpha >= 128 for _, _, _, alpha in pixels]
    count = sum(fg)
    if not 100 < count < width * height - 100:
        raise ValueError("synthetic reference must contain visible foreground and transparent background")
    rgb_rows = [
        bytes(channel for red, green, blue, _alpha in pixels[y * width:(y + 1) * width]
              for channel in (red, green, blue))
        for y in range(height)
    ]
    mask_rows = [bytes(255 if opaque else 0 for opaque in fg[y * width:(y + 1) * width])
                 for y in range(height)]
    depth_rows = [
        b"".join(struct.pack(">H", int((x + y) * 65535 / (width + height - 2)))
                 for x in range(width))
        for y in range(height)
    ]
    root.mkdir(parents=True, exist_ok=True)
    provenance = {"sourceType": "local-procedural-WebGL-oracle", "notPhotographic": True}
    artifacts = [
        artifact(root, "reference", "reference.png",
                 png_bytes(width, height, 8, 2, rgb_rows), width, height, "rgb8-png", provenance),
        artifact(root, "depth", "depth.png",
                 png_bytes(width, height, 16, 0, depth_rows), width, height, "relative-linear-u16-png",
                 {"sourceType": "synthetic-monotonic-ramp", "notInferred": True},
                 sourceRange={"min": 0.0, "max": 1.0}, ordering="lower-value-nearer"),
        artifact(root, "foreground-mask", "foreground-mask.png",
                 png_bytes(width, height, 8, 0, mask_rows), width, height,
                 "mask-u8-png-white-is-1", provenance),
    ]
    manifest = {
        "schemaVersion": 1, "kind": "reconstruction-evidence",
        "bundleId": "synthetic-webgl-silhouette-control",
        "producer": {"runtime": "Chromium", "node": "synthetic-ThreeJS-oracle"},
        "artifacts": artifacts,
        "limitations": [
            "The source is generated by a controlled Three.js fixture, not a user photograph.",
            "The ordinal-depth artifact is a synthetic ramp and has no inferred depth authority.",
            "The evaluator used in the objective-wiring test returns a fixed approved score.",
        ],
    }
    path = root / "manifest.json"
    path.write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    load_bundle(path)
    return path, root / "reference.png", count


def run_experiment(reference_render: Path, matching_render: Path,
                   shifted_render: Path, out_file: Path) -> dict:
    if not all(path.is_file() for path in (reference_render, matching_render, shifted_render)):
        raise ValueError("all three actual Chromium WebGL screenshots must exist")
    source_hash = hashlib.sha256(reference_render.read_bytes()).hexdigest()
    matching_hash = hashlib.sha256(matching_render.read_bytes()).hexdigest()
    shifted_hash = hashlib.sha256(shifted_render.read_bytes()).hexdigest()
    if source_hash != matching_hash or source_hash == shifted_hash:
        raise ValueError("actual browser reference/matching/shifted pixels violate oracle identity")
    root = out_file.parent / "synthetic-bundle"
    manifest, reference, foreground_count = build_synthetic_bundle(root, reference_render)
    loaded = load_bundle(manifest)
    silhouette = prepare_silhouette(loaded, reference)
    matching = silhouette.compare(matching_render, 0.05)
    shifted = silhouette.compare(shifted_render, 0.05)
    if matching["iou"] < 0.98 or shifted["iou"] > matching["iou"] - 0.05:
        raise ValueError("real WebGL silhouette scorer did not discriminate a known position error")

    # All three arms use these SAME real-browser output files. The evaluator is
    # deliberately a fixed APPROVED fixture score, never called Divine Eye evidence.
    def render(parameters):
        return matching_render if parameters[0] < 1.0 else shifted_render

    def frozen_evaluator(_reference, _render):
        return {"fidelity": 0.8, "hardGateFailures": [], "verdict": "pass", "action": "continue"}

    options = dict(
        initial=[1.0], bounds=[[0.0, 2.0]], render_for_parameters=render,
        reference_png=reference, evaluator=frozen_evaluator,
        config=FitConfig(max_iterations=1, max_evaluations=3, seed=7),
    )
    # The shadow-comparison CLI consumes JSON loaded from disk. The fitter's
    # in-memory to_json() retains tuples, so cross the same JSON wire boundary
    # before comparing exact candidate sequences and receipts.
    baseline = json.loads(json.dumps(fit_against_divine_eye(**options).to_json(), allow_nan=False))
    shadow = json.loads(json.dumps(fit_against_divine_eye(**options, evidence_manifest=manifest).to_json(), allow_nan=False))
    parity = compare_shadow_runs(baseline, shadow)
    if not parity["parity"]:
        raise ValueError("receipt-only evidence unexpectedly altered the fitting process")
    experimental = json.loads(json.dumps(fit_against_divine_eye(
        **options, evidence_manifest=manifest, experimental_silhouette_weight=0.05
    ).to_json(), allow_nan=False))
    base_evaluations = baseline["fitResult"]["evaluations"]
    shadow_evaluations = shadow["fitResult"]["evaluations"]
    experimental_evaluations = experimental["fitResult"]["evaluations"]
    if (base_evaluations, shadow_evaluations, experimental_evaluations) != (3, 3, 3):
        raise ValueError("fit arms used different render evaluation budgets")
    best_baseline = baseline["fitResult"]["parameters"]
    best_experiment = experimental["fitResult"]["parameters"]
    if not (best_baseline == [1.0] and best_experiment == [0.5]):
        raise ValueError("experimental scorer did not change the controlled candidate ranking")
    if experimental["bestRawFidelity"] != baseline["bestRawFidelity"]:
        raise ValueError("silhouette evidence modified the evaluator's raw fidelity")
    report = {
        "schemaVersion": 1, "fixtureClass": "synthetic-independent-webgl-reference",
        "actualBrowserRendering": True, "photographicReconstruction": False,
        "realDA3Inference": False, "independentFidelityEvaluation": False,
        "shadowParity": parity["parity"],
        "matchingIoU": matching["iou"], "shiftedIoU": shifted["iou"],
        "foregroundPixels": foreground_count,
        "evaluationsPerArm": 3,
        "baselineParameters": best_baseline, "experimentalParameters": best_experiment,
        "experimentalSelectedBetterCandidate": best_experiment == [0.5],
        "rawFidelityBaseline": baseline["bestRawFidelity"],
        "rawFidelityExperiment": experimental["bestRawFidelity"],
        "sourcePngSha256": source_hash,
        "matchingPngSha256": matching_hash,
        "shiftedPngSha256": shifted_hash,
        "evidenceManifestSha256": hashlib.sha256(manifest.read_bytes()).hexdigest(),
    }
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference-render", required=True, type=Path)
    parser.add_argument("--matching-render", required=True, type=Path)
    parser.add_argument("--shifted-render", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    try:
        report = run_experiment(args.reference_render, args.matching_render, args.shifted_render, args.out)
        print(json.dumps({"status": "PASS", "matchingIoU": report["matchingIoU"],
                          "shiftedIoU": report["shiftedIoU"], "shadowParity": report["shadowParity"]}))
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"browser evidence smoke: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
